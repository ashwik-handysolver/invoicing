-- Invoicing app schema for Supabase Postgres. Idempotent: the server runs it on start.
-- Dates/timestamps are kept as ISO text ('YYYY-MM-DD' / 'YYYY-MM-DD HH:MM:SS' UTC), as the app has always stored them.
-- Row Level Security is on for every table with no policies: only the server (database owner) can read or write;
-- Supabase's public API keys get nothing.

create schema if not exists extensions;
create extension if not exists citext with schema extensions;

-- days since 4714 BC, like SQLite's julianday(): used for "average days to pay"
create or replace function public.julianday(t text) returns double precision
  language sql immutable set search_path = '' as $$ select extract(epoch from t::timestamp) / 86400.0 + 2440587.5 $$;

create or replace function public.utc_now_text() returns text
  language sql stable set search_path = '' as $$ select to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS') $$;

create table if not exists users (
  id integer generated by default as identity primary key,
  name text not null,
  email extensions.citext not null unique,
  password_hash text not null,
  role_id integer,
  active integer not null default 1,
  created_at text default utc_now_text(),
  is_management integer not null default 0
);

create table if not exists tenants (
  id integer generated by default as identity primary key,
  name text not null,
  invite_code text not null unique,
  created_by integer references users(id) on delete set null,
  created_at text default utc_now_text(),
  modules text,
  active integer not null default 1,
  is_platform integer not null default 0
);

create table if not exists roles (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  name text not null,
  permissions text not null default '[]',
  unique (tenant_id, name)
);

do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'users_role_id_fkey') then
    alter table users add constraint users_role_id_fkey foreign key (role_id) references roles(id) on delete set null;
  end if;
end $$;

create table if not exists memberships (
  id integer generated by default as identity primary key,
  tenant_id integer not null references tenants(id) on delete cascade,
  user_id integer not null references users(id) on delete cascade,
  role text not null default 'member' check (role in ('admin', 'member')),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at text default utc_now_text(),
  decided_at text,
  decided_by integer references users(id) on delete set null,
  role_id integer references roles(id) on delete set null,
  unique (tenant_id, user_id)
);
-- a user belongs to (or is waiting for) at most one organisation at a time
create unique index if not exists idx_member_active on memberships(user_id) where status in ('pending', 'approved');
create index if not exists idx_member_tenant on memberships(tenant_id, status);

create table if not exists sessions (
  token text primary key,
  user_id integer not null references users(id) on delete cascade,
  created_at text default utc_now_text(),
  tenant_id integer references tenants(id) on delete cascade
);

create table if not exists settings (
  tenant_id integer not null default 0,
  key text not null,
  value text,
  primary key (tenant_id, key)
);

create table if not exists organisations (
