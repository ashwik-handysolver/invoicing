  tenant_id integer references tenants(id) on delete cascade,
  name text not null,
  address text, state text, state_code text,
  gst_number text, pan_number text, email text, contact text,
  bank_details text, logo text, signature text, footer_note text, terms text, upi_id text, qr_image text
);

create table if not exists clients (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  created_at text default utc_now_text(),
  name text not null,
  address text, state text, state_code text,
  gst_number text, pan_number text, email text, mobile text,
  contact_person text,
  status text not null default 'active'
);

create table if not exists service_products (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  name text not null,
  sac_number text, description text,
  price double precision default 0, tax double precision default 18
);

create table if not exists invoices (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  created_at text default utc_now_text(),
  created_by integer,
  invoice_type text not null check (invoice_type in ('proforma', 'tax')),
  invoice_number text not null,
  invoice_series_int integer not null,
  fy text not null,
  invoice_date text not null,
  due_date text,
  organisation_id integer not null references organisations(id),
  client_id integer not null references clients(id),
  org_name text, org_address text, org_email text, org_contact text, org_gst text, org_bank text,
  client_name text, client_address text, client_email text, client_contact text, client_gst text,
  place_of_supply text,
  gross_amount double precision default 0, discount_amount double precision default 0, selling_amount double precision default 0,
  igst double precision default 0, cgst double precision default 0, sgst double precision default 0,
  tds_percent double precision default 0, tds_amount double precision default 0,
  total_amount double precision default 0, net_amount double precision default 0,
  paid_amount double precision default 0, balance_amount double precision default 0,
  payment_status text not null default 'unpaid',
  converted_to_id integer, converted_from_id integer,
  notes text,
  credit_amount double precision default 0,
  share_token text, viewed_at text, view_count integer default 0,
  gst_applied integer default 1, pay_qr integer default 1, pay_upi integer default 1, pay_bank integer default 1,
  unique (organisation_id, invoice_number)
);
create index if not exists idx_inv_client on invoices(client_id);
create index if not exists idx_inv_date on invoices(invoice_date);
create index if not exists idx_invoices_tenant on invoices(tenant_id);
create unique index if not exists idx_inv_share on invoices(share_token) where share_token is not null;

create table if not exists invoice_items (
  id integer generated by default as identity primary key,
  invoice_id integer not null references invoices(id) on delete cascade,
  service_product_id integer,
  position integer,
  sac_number text, description text,
  price double precision, quantity double precision,
  gross_amount double precision, discount_percent double precision, discount_amount double precision, selling_amount double precision,
  tax double precision, igst double precision, cgst double precision, sgst double precision, total_amount double precision
);
create index if not exists idx_items_invoice on invoice_items(invoice_id);

create table if not exists payments (
  id integer generated by default as identity primary key,
  invoice_id integer not null references invoices(id) on delete cascade,
  amount double precision not null,
  paid_on text not null,
  mode text, reference text, notes text,
  created_by integer,
  created_at text default utc_now_text()
);
create index if not exists idx_payments_invoice on payments(invoice_id);

create table if not exists message_templates (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  name text not null,
  channel text not null check (channel in ('whatsapp', 'email')),
  kind text not null default 'reminder' check (kind in ('reminder', 'invoice', 'receipt')),
  subject text,
  body text not null
);

create table if not exists reminder_log (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  client_id integer, invoice_id integer,
  channel text, template_id integer, sent_by integer,
  created_at text default utc_now_text(),
  rule integer
);

create table if not exists email_notify (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  email text not null
);

create table if not exists recurring_invoices (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  created_at text default utc_now_text(), created_by integer,
  organisation_id integer not null, client_id integer not null,
  invoice_type text not null default 'tax',
  frequency text not null, start_date text not null, next_run text not null, end_date text,
  due_days integer default 7, tds_percent double precision default 0, notes text, items_json text not null,
  active integer not null default 1, run_count integer not null default 0,
  last_invoice_id integer, last_run_at text, source_invoice_id integer,
  gst_applied integer default 1, pay_qr integer default 1, pay_upi integer default 1, pay_bank integer default 1
);

create table if not exists credit_notes (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  created_at text default utc_now_text(), created_by integer,
  number text not null, fy text not null, series_int integer not null,
  note_date text not null, invoice_id integer not null references invoices(id) on delete cascade,
  organisation_id integer not null, reason text,
  taxable double precision default 0, tax_rate double precision default 0,
  igst double precision default 0, cgst double precision default 0, sgst double precision default 0, total double precision default 0
);

create table if not exists expenses (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  created_at text default utc_now_text(),
  date text not null, category text, vendor text, amount double precision not null default 0, notes text
);

create table if not exists activity_log (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  created_at text default utc_now_text(),
  user_id integer, user_name text, action text, entity text, entity_id integer, summary text
);
create index if not exists idx_act_created on activity_log(created_at);

create table if not exists tasks (
  id integer generated by default as identity primary key,
  tenant_id integer references tenants(id) on delete cascade,
  title text not null,
  description text,
  due_date text,
  priority text not null default 'medium',
  status text not null default 'todo',
  assigned_to integer references users(id) on delete set null,
  assigned_by integer references users(id) on delete set null,
  created_at text default utc_now_text()
);

create table if not exists task_assignees (
  task_id integer not null references tasks(id) on delete cascade,
  user_id integer not null references users(id) on delete cascade,
  primary key (task_id, user_id)
);
create index if not exists idx_task_assignees_user on task_assignees(user_id);

-- tenant_id lookups
do $$ declare t text; begin
  foreach t in array array['organisations','clients','service_products','message_templates','reminder_log','email_notify',
    'recurring_invoices','credit_notes','expenses','activity_log','tasks','roles'] loop
    execute format('create index if not exists idx_%s_tenant on %I(tenant_id)', t, t);
  end loop;
end $$;

-- Lock every table to the server: RLS on, no policies.
do $$ declare t text; begin
  for t in select tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table %I enable row level security', t);
  end loop;
end $$;
